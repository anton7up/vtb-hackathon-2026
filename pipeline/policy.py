#!/usr/bin/env python
"""
Политика решений: вероятность фрода -> действие 0/1/2.

Почему отдельно от модели
-------------------------
Модель отвечает на вопрос «какая вероятность фрода». Что с этой вероятностью
делать — решает банк: пропустить, отправить на ручную проверку или заблокировать.
Это бизнес-правило, а не математика, поэтому оно живёт в отдельном файле
и не требует переобучения при изменении порогов.

Пороги приходят из `artifacts/thresholds.json`:

    t_review = 0.14  — ниже этого пропускаем
    t_block  = 0.46  — выше этого блокируем

Зоны:

    p < t_review            -> 0 (пропустить)
    t_review <= p < t_block -> 1 (проверить вручную)
    p >= t_block            -> 2 (заблокировать)
"""

from __future__ import annotations

import numpy as np


def make_decision(proba, t_review: float, t_block: float):
    """Превращает вероятность (или массив вероятностей) в решение 0/1/2.

    Работает векторизованно: на вход можно подать одно число, список,
    numpy-массив или pandas Series — вернётся numpy-массив той же длины.

    `np.where(условие, если_да, если_нет)` — это поэлементный `if`.
    Выражение вложенное, поэтому читается изнутри наружу:

        внутренний слой: p < t_block ? 1 : 2
        внешний слой:   p < t_review ? 0 : <результат внутреннего>

    Сравнение строгое (`<`): ровно 0.14 попадёт в проверку, ровно 0.46 —
    в блокировку. На реальных данных такие совпадения почти не встречаются,
    но при отладке об этом стоит помнить.

    Про NaN: любое сравнение с NaN даёт False, поэтому пропуск в вероятности
    уйдёт в самый низ и превратится в 2 — молчаливую блокировку. Поэтому
    вызывающий код обязан проверить NaN заранее (см. predict_example.py).
    """
    if t_block <= t_review:
        raise ValueError(
            f"Пороги перепутаны: t_block={t_block} должен быть больше "
            f"t_review={t_review}. Иначе зона проверки исчезает."
        )

    return np.where(proba < t_review, 0, np.where(proba < t_block, 1, 2))
